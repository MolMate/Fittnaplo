const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(require('node:path').join(__dirname,'..','app.js'),'utf8');
const sandbox={window:{addEventListener(){}},document:{},console,Intl,Date,Math,Number,String,Set,Map,Promise,globalThis:undefined};
vm.createContext(sandbox);vm.runInContext(source,sandbox);
const run=code=>vm.runInContext(code,sandbox);
assert.equal(run('DB_VERSION'),2);
assert.equal(run('STORE_NAMES.includes("plans")'),true);
assert.equal(run('bmiMeaning(18.49).label'),'Soványság');
assert.equal(run('bmiMeaning(18.5).label'),'Normál testsúly tartomány');
assert.equal(run('bmiMeaning(24.99).label'),'Normál testsúly tartomány');
assert.equal(run('bmiMeaning(25).label'),'Túlsúly tartomány');
assert.equal(run('bmiMeaning(30).label'),'Elhízás, I. fokozat');
assert.equal(run('fatMeaning(16,"male").label'),'Fittségi referencia-tartomány');
assert.equal(run('fatMeaning(30,"female").label'),'Általános referencia-tartomány');
const old={app:'FitNapló',schemaVersion:1,profile:{id:'main',height:181,sex:'male',goal:null,name:''},weights:[{date:'2026-11-21',weight:85}],measurements:[],workouts:[{id:'abc',date:'2026-11-21',name:'Fekvenyomás',sets:3,reps:8,weight:60,note:''}]};
sandbox.backup=old;
assert.equal(run('validateBackup(backup).plans.length'),0);
assert.equal(run('validateBackup(backup).workouts.length'),1);
const newer={...old,schemaVersion:2,plans:[{id:'plan-1',name:'Felsőtest',exercises:[{id:'ex-1',name:'Fekvenyomás'}]}]};
sandbox.backup=newer;
assert.equal(run('validateBackup(backup).plans[0].exercises[0].name'),'Fekvenyomás');
sandbox.backup={...newer,plans:[{id:'plan-1',name:'A',exercises:[{id:'ex-1',name:'Fekvenyomás'},{id:'ex-1',name:'Evezés'}]}]};
assert.throws(()=>run('validateBackup(backup)'),/Hibás edzésterv-gyakorlat/);
console.log('PASS: DB schema upgrade, BMI and fat descriptions, v1/v2 backups, duplicate plan validation');
